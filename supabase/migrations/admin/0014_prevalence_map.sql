-- admin/0014 · STH prevalence map: an area lookup and the figures per region, province and town
--
-- Run via: Supabase dashboard → SQL Editor → paste → Run. By hand, once.
-- Requires: admin/0001_organizations.sql (patient_organizations, console_org_admin_org()),
-- admin/0002_patient_scoping.sql, admin/0011_dashboard_totals.sql (the counting rule this
-- repeats), and the app's 0014_super_admins.sql (is_admin()).
--
-- ── Why (14zcqntjnt3) ────────────────────────────────────────────────────────
-- The map shades the Philippines by the share of examined smears that were positive, and an admin
-- drills Region → Province → City/Municipality. Every figure is counted here, per area, so the
-- console never adds up patient rows (R3). `barangay_prevalence()` cannot be summed instead: it
-- withholds a barangay under 5 smears, so its rows undercount every province they fall in.
--
-- ── The lookup (psgc_regions, psgc_provinces, psgc_towns, psgc_town_aliases) ─
-- The database had no way to place a barangay code: the PSGC list lives on the phone. These four
-- tables hold the 2Q 2026 release's 18 regions, 85 province-level areas and 1,642 cities and
-- municipalities, the same ones the map's outlines carry, generated by
-- scripts/geo/build-map-data.ts from the app repo's tools/geo and tools/psgc. Each town has one
-- province-level parent: a highly urbanised city sits in the province around it, and NCR's towns
-- in an NCR area (1300000000) as the app's map does.
--   * Barangay → town is a rule, not 42,010 rows (console_psgc_town()): the first seven digits
--     and 000, except the City of Manila, whose 897 barangays sit under districts. The build
--     script checks the rule against every barangay in the release and stops if one breaks it.
--   * Negros Island Region and Sulu were renumbered after 2023. A patient recorded with a 2023
--     code is found through psgc_town_aliases (82 towns) and lands under the current region.
--   * A code that matches no town is "not placed on the map": counted in the country's figures
--     line, never guessed into an area.
-- Reference data, not patient data, but read only through the function below: row level
-- security on, no policy, no client privilege, as the console's other tables.
--
-- ── console_area_prevalence(level, code, organization, from, to) ────────────
-- One area and every area one level down: the country and its regions, a region and its
-- provinces, a province and its towns. Each with examined smears and positive smears, counted
-- by console_dashboard_figures()'s rule (admin/0011): the session is the smear; examined once a
-- live sample exists; positive when a live sample carries a detection other than FALSE_POSITIVE.
-- So the country's examined smears plus those not placed equal the dashboard's for the same
-- scope and period.
--
-- Small areas are protected at every level: an area with 1 to 4 examined smears comes back as
-- suppressed, with no figures (console_area_figure()). The threshold is barangay_prevalence()'s,
-- 5, applied to the area's own count, so a province built from small barangays shows its figure
-- once it reaches 5, and a small province is withheld whatever its barangays hold. An area with
-- none is 0, which identifies no one, and the map tells it apart from "too few". A withheld
-- area's count can sometimes be had by subtracting its shown siblings from its parent; that was
-- accepted for this map, whose readers are the console's admins.
--
-- Scope is decided here, as console_dashboard_figures() decides it: a super admin all
-- laboratories or one; an organization admin their own only (another is 42501); anyone else
-- refused. An unknown area is P0002, a bad level 22023. Security definer, because a super
-- admin's table reads return nothing since app 0013; it returns counts and area names only.
--
-- Additive only: four tables of this repo's own and three functions. Nothing the app owns is
-- altered.

begin;

create table public.psgc_regions (
    code text primary key check (code ~ '^\d{10}$'),
    name text not null
);

create table public.psgc_provinces (
    code        text primary key check (code ~ '^\d{10}$'),
    name        text not null,
    region_code text not null references public.psgc_regions(code)
);

create table public.psgc_towns (
    code          text primary key check (code ~ '^\d{10}$'),
    name          text not null,
    province_code text not null references public.psgc_provinces(code)
);
create index psgc_towns_province_idx on public.psgc_towns (province_code);

-- 2023-vintage town code → its current town, for the renumbered regions.
create table public.psgc_town_aliases (
    old_code text primary key check (old_code ~ '^\d{10}$'),
    code     text not null references public.psgc_towns(code)
);

alter table public.psgc_regions      enable row level security;
alter table public.psgc_provinces    enable row level security;
alter table public.psgc_towns        enable row level security;
alter table public.psgc_town_aliases enable row level security;
revoke all on public.psgc_regions, public.psgc_provinces, public.psgc_towns,
              public.psgc_town_aliases from public, anon, authenticated;

